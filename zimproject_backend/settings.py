def _normalize_samesite(name, value, secure, default="Lax"):
    raw = (value or "").strip()
    if not raw:
        raw = default
    lowered = raw.lower()
    if lowered == "none":
        if not secure:
            warnings.warn(
                f"{name}=None requires Secure cookies; falling back to Lax for non-HTTPS environments.",
                RuntimeWarning,
            )
            return "Lax"
        return "None"
    if lowered == "lax":
        return "Lax"
    if lowered == "strict":
        return "Strict"
    return raw

